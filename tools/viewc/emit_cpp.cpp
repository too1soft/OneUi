std::string quote(const std::string &s) {
    std::ostringstream out;out << '"';
    for(unsigned char c:s) {
        if(c=='"' || c=='\\') out << '\\' << c;
        else if(c=='\n') out << "\\n";
        else if(c=='\r') out << "\\r";
        else out << c;
    }
    return out.str()+'"';
}
const char *value(uint32_t tag) {
    return tag==1 ? "boolean" : tag==2 ? "integer" : tag==3 ? "number" : "string";
}
void model(std::ostream &out,const Schema &schema,const Model &m) {
    out << "template<class V> std::shared_ptr<A> model_" << m.id << "(std::shared_ptr<V> vm) {\n"
        << "    auto a=std::make_shared<A>(schema_hash," << m.id << "); a->owner=vm;\n"
        << "    a->get=[vm](uint32_t id)->oneui::ui::view::Value { using namespace oneui::ui::view; switch(id) {\n";
    for(const auto &[_,p]:m.properties)
        if(p.tag!=5)out << "    case " << p.id << ": return Value::" << value(p.tag) << "(field(vm->" << p.name << "));\n";
    out << "    default: throw std::invalid_argument(\"Unknown property\"); } };\n"
        << "    a->set=[vm](uint32_t id,const OneUiValue &v)->int { switch(id) {\n";
    for(const auto &[_,p]:m.properties)if(p.access==3)
        out << "    case " << p.id << ": oneui::ui::view::assign(vm->" << p.name << ",v);return 0;\n";
    out << "    default:return ONEUI_VIEW_READ_ONLY; } };\n"
        << "    a->invoke=[vm](uint32_t id,const OneUiValue *args,size_t argc)->int { switch(id) {\n";
    for(const auto &[_,c]:m.commands) {
        out << "    case " << c.id << ": if(argc!=" << c.args.size() << ")return ONEUI_VIEW_TYPE; ";
        for(size_t i=0;i<c.args.size();++i)
            out << "if(args[" << i << "].tag!=" << c.args[i].tag << ")return ONEUI_VIEW_TYPE; ";
        if(c.args.empty())out << "vm->" << c.name << ".execute();";
        else {
            out << "vm->" << c.name << "(";
            for(size_t i=0;i<c.args.size();++i) {
                if(i)out << ',';
                auto arg="args["+std::to_string(i)+"]";
                if(c.args[i].tag==4)out << "oneui::ui::view::text(" << arg << ")";
                else out << arg << (c.args[i].tag==1 ? ".as.boolean!=0" : c.args[i].tag==2 ? ".as.integer" : ".as.number");
            }
            out << ");";
        }
        out << "return 0;\n";
    }
    out << "    default:return ONEUI_VIEW_UNKNOWN_ID; } };\n"
        << "    a->subscribe=[vm](A &a,oneui::ui::view::Connection &c) {\n";
    for(const auto &[_,p]:m.properties)
        out << "        oneui::ui::view::watch(vm->" << p.name << ",a,c," << p.id << ");\n";
    out << "    };\n";
    for(const auto &[_,p]:m.properties)if(p.tag==5) {
        const auto &item=schema.model(p.item);
        if(item.name.rfind("oneui.v1.",0)==0) {
            auto kind=item.name.substr(9);
            const std::map<std::string,std::string> conversions={{"StringItem","stringRecord"},{"NumberItem","numberRecord"},
                {"Column","columnRecord"},{"Row","rowRecord"},{"TabItem","tabRecord"},{"Series","seriesRecord"}};
            out << "    oneui::ui::view::recordList(*a," << p.id << ",vm->" << p.name
                << ",[](const auto &v,size_t i) { return oneui::ui::view::" << conversions.at(kind)
                << "(v,i); },[](auto item) { return model_" << item.id << "(item); });\n";
        } else out << "    oneui::ui::view::list(*a," << p.id << ",vm->" << p.name
            << ",[](const auto &item) { return oneui::ui::view::field(item->" << item.keyName
            << "); },[](auto item) { return model_" << item.id << "(item); });\n";
    }
    out << "    return a;\n}\n";
}
