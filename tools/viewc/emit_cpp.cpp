std::string emitCpp(const Image &image,const Bytes &bytes,const std::string &name,const std::string &header,
                    const std::filesystem::path &sourceDirectory) {
    std::ostringstream out;
    out << "// Generated by oneui-viewc. One IR for every language.\n#pragma once\n#include \"oneui/view_cpp_records.h\"\n";
    if(!header.empty())out << "#include " << quote(header) << '\n';
    out << "namespace oneview_" << name << " {\nusing A=oneui::ui::view::Adapter;\ninline constexpr uint8_t ir[]={\n";
    for(size_t i=0;i<bytes.size();++i)out << unsigned(bytes[i]) << ',' << (i%24==23 ? "\n" : "");
    out << "\n};\ninline constexpr uint8_t schema_hash[]={";
    for(auto b:sha256(image.schema.encode()))out << unsigned(b) << ',';
    out << "};\n";
    for(const auto &[_,m]:image.schema.models)
        out << "template<class V> std::shared_ptr<A> model_" << m.id << "(std::shared_ptr<V>);\n";
    for(const auto &[_,m]:image.schema.models)model(out,image.schema,m);
    out << "}\ntemplate<class VM> oneui::ui::Element build_" << name << "(std::shared_ptr<VM> vm,oneui::ui::Mount &ui) {\n"
        << "    using namespace oneview_" << name << ";auto adapter=model_" << image.schema.root << "(std::move(vm));\n"
        << "    return oneui::ui::view::mount(ui,ir,sizeof(ir),&adapter->table,adapter.get());\n}\n"
        << "// Borrowed VM must outlive Mount; prefer the shared_ptr overload.\n"
        << "template<class VM> oneui::ui::Element build_" << name << "(VM &vm,oneui::ui::Mount &ui) {\n"
        << "    return build_" << name << "(std::shared_ptr<VM>(&vm,[](VM*){}),ui);\n}\n";
    std::string css;
    for(auto &r:image.records.at(CSS))css+=image.strings[r[2]]+'\n';
    out << "inline std::string styles_" << name << "() { return " << quote(css) << "; }\n";
    out << "inline std::vector<std::pair<std::string,std::string>> sources_" << name << "() { return {";
    std::set<std::string> sources;
    for(auto &r:image.records.at(SMAP))sources.insert(image.strings[r[0]]);
    for(const auto &file:sources) {
        Bytes seed(file.begin(),file.end());seed.push_back(0);
        auto stem=std::filesystem::path(file).stem().generic_string();
        seed.insert(seed.end(),stem.begin(),stem.end());
        out << '{' << quote((sourceDirectory/file).generic_string()) << ','
            << quote("one-s-"+hex(sha256(seed)).substr(0,16)) << "},";
    }
    out << "}; }\ninline std::string scope_" << name << "(const std::string &file) {\n";
    for(const auto &file:sources) {
        Bytes seed(file.begin(),file.end());seed.push_back(0);
        auto stem=std::filesystem::path(file).stem().generic_string();
        seed.insert(seed.end(),stem.begin(),stem.end());
        out << "if(file==" << quote(file) << ")return " << quote("one-s-"+hex(sha256(seed)).substr(0,16)) << ";\n";
    }
    out << "throw std::invalid_argument(\"Unknown template source\"); }\n";
    return out.str();
}
