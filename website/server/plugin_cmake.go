package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func cmakeLiteral(value string) string {
	value = filepath.ToSlash(value)
	separator := "="
	for strings.Contains(value, "]"+separator+"]") {
		separator += "="
	}
	return "[" + separator + "[" + value + "]" + separator + "]"
}
func generatePluginCMake(directory, target string, project PluginProject, lock PluginTargetLock, paths map[string]string) (string, error) {
	order, err := pluginOrder(lock.Packages)
	if err != nil {
		return "", err
	}
	var source strings.Builder
	source.WriteString("# Generated by oneui-site plugin restore. Regenerate after moving a project.\ninclude_guard(DIRECTORY)\n")
	declaration, _ := json.MarshalIndent(project, "", "  ")
	declaration = append(declaration, '\n')
	fmt.Fprintf(&source, "file(SHA256 %s _oneui_plugin_project_hash)\nif(NOT _oneui_plugin_project_hash STREQUAL %s)\n  message(FATAL_ERROR \"Plugin declarations changed; run oneui-site plugin restore\")\nendif()\n", cmakeLiteral(filepath.Join(directory, "oneui.plugins.json")), cmakeLiteral(hashBytes(declaration)))
	for _, id := range order {
		p := lock.Packages[id]
		if p.Source.Path == "" && p.Source.Git == "" {
			fmt.Fprintf(&source, "list(PREPEND CMAKE_PREFIX_PATH %s)\n", cmakeLiteral(paths[id]))
		}
	}
	var targets, components []string
	for _, id := range order {
		p := lock.Packages[id]
		if p.Source.Path != "" || p.Source.Git != "" {
			fmt.Fprintf(&source, "add_subdirectory(%s \"${CMAKE_CURRENT_BINARY_DIR}/oneui-plugins/%s\")\n", cmakeLiteral(paths[id]), id)
		} else {
			fmt.Fprintf(&source, "find_package(%s CONFIG REQUIRED)\n", p.Manifest.CMakePackage)
		}
		if p.Manifest.Kind == "component" {
			components = append(components, p.Manifest.CMakeTarget)
		} else if p.Manifest.Kind != "sdk" {
			targets = append(targets, p.Manifest.CMakeTarget)
		}
	}
	fmt.Fprintf(&source, "set(ONEUI_PLUGIN_TARGETS %s)\n", strings.Join(targets, " "))
	fmt.Fprintf(&source, "set(ONEUI_COMPONENT_TARGETS %s)\n", strings.Join(components, " "))
	output := filepath.Join(directory, ".oneui", "plugins", target, "OneUIProjectPlugins.cmake")
	if err = os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return "", err
	}
	if err = atomicWrite(output, []byte(source.String())); err != nil {
		return "", err
	}
	return output, nil
}
