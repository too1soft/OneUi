"""Merge viewc requirements into a deterministic per-target selection header."""
import argparse
import json
import re
from pathlib import Path


def merge(manifests, extra=(), full=False):
    selected, available = set(extra), set()
    for file in manifests:
        data = json.loads(Path(file).read_text(encoding="utf-8"))
        if data.get("format_version") != 1:
            raise ValueError(f"Unsupported view requirements: {file}")
        selected.update(data["components"])
        available.update(data["available_components"])
        full |= data["full_runtime"]
    if not available:
        raise ValueError("No view requirements supplied")
    unknown = set(extra) - available
    if unknown:
        raise ValueError("Unknown dynamic components: " + ", ".join(sorted(unknown)))
    # Explicit dynamic components may themselves be composites. Their closure
    # cannot be inferred here; retain the full runtime rather than guess.
    if full or extra:
        selected.update(available)
    for name in available | selected:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            if name in available:
                raise ValueError(f"Invalid built-in component identifier: {name}")
    lines = ["// Generated by OneUI. Do not edit.", "#pragma once", "#include <string_view>"]
    for name in sorted(available):
        lines.append(f"#define ONEUI_COMPONENT_ENABLED_{name} {int(name in selected)}")
    lines.append("namespace oneui::ui::detail {")
    lines.append("inline bool componentSelected(std::string_view name) {")
    names = [name for name in sorted(selected) if name in available]
    lines.append("return " + " || ".join('name == "' + name + '"' for name in names) + ";")
    lines.append("}\n}")
    return "\n".join(lines) + "\n", sorted(selected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifests", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--extra", default="")
    parser.add_argument("--full", action="store_true")
    args = parser.parse_args()
    paths = [p for p in Path(args.manifests).read_text(encoding="utf-8").splitlines() if p]
    header, _ = merge(paths, [p for p in args.extra.split(",") if p], args.full)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != header:
        output.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
